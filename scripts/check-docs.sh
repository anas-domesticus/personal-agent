#!/usr/bin/env bash
# Fails if a package has no package comment, or if docs/architecture.md doesn't
# mention a package under internal/. Run by `task docs:check` and `task check`.
set -euo pipefail
cd "$(dirname "$0")/.."

module=$(go list -m)
fail=0
while IFS='|' read -r pkg doc; do
	rel=${pkg#"$module"/}
	[[ "$rel" == internal/store/db ]] && continue # generated by sqlc
	if [[ -z "$doc" ]]; then
		echo "missing package comment: $rel"
		fail=1
	fi
	case "$rel" in
	internal/*)
		if ! grep -q "$rel" docs/architecture.md; then
			echo "docs/architecture.md doesn't mention $rel"
			fail=1
		fi
		;;
	esac
done < <(go list -f '{{.ImportPath}}|{{.Doc}}' ./...)
exit $fail
